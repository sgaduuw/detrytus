#!/bin/sh
# Rebuild lower/float.ll: the software floating point detrytus ll
# links into programs that use float or double (docs/rust.md, Floating
# point), taken from the compiler_builtins that rustc builds beside core
# for riscv32imac-unknown-none-elf. Needs what regenerate.sh needs:
#   rustup target add riscv32imac-unknown-none-elf
#   rustup component add rust-src
set -eu
here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../../../../.." && pwd)
work=${TMPDIR:-/tmp}/detrytus-float
mkdir -p "$work/src"
cat > "$work/Cargo.toml" <<'TOML'
[package]
name = "floats"
version = "0.1.0"
edition = "2024"
[lib]
crate-type = ["staticlib"]
[profile.release]
opt-level = "s"
panic = "abort"
codegen-units = 1
TOML
echo '#![no_std]' > "$work/src/lib.rs"
(cd "$work" && RUSTC_BOOTSTRAP=1 \
    RUSTFLAGS="--emit=llvm-ir,link -Zunstable-options -Cpanic=immediate-abort" \
    cargo build --quiet --release -Zbuild-std=core --target riscv32imac-unknown-none-elf)
release="$work"/target/riscv32imac-unknown-none-elf/release
cb=$(ls -t $(find "$release" -name 'compiler_builtins-*.ll') | head -1)
core=$(ls -t $(find "$release" -name 'core-*.ll') | head -1)
roots=""
for t in sf df; do
    for f in add sub mul div; do roots="$roots __$f${t}3"; done
    for f in eq ne lt le gt ge unord; do roots="$roots __$f${t}2"; done
    for i in si di ti; do
        roots="$roots __fix$t$i __fixuns$t$i __float$i$t __floatun$i$t"
    done
done
roots="$roots __extendsfdf2 __truncdfsf2"
for f in fmod floor ceil trunc round roundeven rint sqrt fma fmin fmax \
    fminimum fmaximum fminimum_num fmaximum_num; do
    roots="$roots $f ${f}f"
done
args=""
for r in $roots; do args="$args --root $r"; done
out="$here/float.ll"
cargo run --quiet --release --manifest-path "$root/Cargo.toml" -p detrytus-cli -- \
    ll --prune $args "$cb" "$core" -o "$out.body"
{
    echo "; Software floating point for detrytus ll (docs/rust.md, Floating point),"
    echo "; generated by float.sh from the compiler_builtins crate that rustc"
    echo "; $(rustc --version | cut -d' ' -f2) builds for riscv32imac-unknown-none-elf."
    echo "; compiler_builtins is the Rust project's, licensed MIT AND"
    echo "; Apache-2.0 WITH LLVM-exception AND (MIT OR Apache-2.0); its libm"
    echo "; part comes from musl (MIT). See"
    echo "; https://github.com/rust-lang/compiler-builtins for the source and"
    echo "; the licence texts."
    sed "s|$(dirname "$cb")/||g; s|$(dirname "$core")/||g" "$out.body"
} > "$out"
rm "$out.body"
echo "$out"
